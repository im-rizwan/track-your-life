export class ReferenceService {
  async getPrayerStatuses() {
    return prisma.prayerStatus.findMany({
      where: { isActive: true },
      orderBy: { sortOrder: 'asc' },
    });
  }

  async getQuranActivityTypes() {
    return prisma.quranActivityType.findMany({
      where: { isActive: true },
      orderBy: { sortOrder: 'asc' },
    });
  }

  async getTaskPriorities() {
    return prisma.taskPriority.findMany({
      where: { isActive: true },
      orderBy: { sortOrder: 'asc' },
    });
  }

  async getTaskStatuses() {
    return prisma.taskStatus.findMany({
      where: { isActive: true },
      orderBy: { sortOrder: 'asc' },
    });
  }

  async getFitnessIntensities() {
    return prisma.fitnessIntensity.findMany({
      where: { isActive: true },
      orderBy: { sortOrder: 'asc' },
    });
  }

  getSurahs(): Surah[] {
    return SURAHS;
  }

  getJuzz(): Juzz[] {
    return Array.from({ length: 30 }, (_, i) => ({ number: i + 1 }));
  }

  getCountries(): Country[] {
    return [...COUNTRIES].sort((a, b) => a.name.localeCompare(b.name));
  }
}
